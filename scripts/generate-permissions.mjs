import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'

/** Regenerates src/types/permissions.generated.ts from public.permissions.
 *
 *  Read-only against the database: a single SELECT. The union exists so a
 *  typo in a permission key fails compilation rather than silently denying
 *  access at runtime, which is the failure mode that looks like a bug report
 *  about a missing menu item.
 *
 *  Usage: npm run db:permissions
 */
const SQL = "select key from public.permissions order by key;"

const raw = execFileSync(
  'docker',
  ['exec', 'supabase_db_jmac-suite', 'psql', '-U', 'postgres', '-d', 'postgres', '-tAc', SQL],
  { encoding: 'utf8' }
)

const keys = raw
  .split('\n')
  .map((line) => line.trim())
  .filter(Boolean)

if (keys.length === 0) {
  console.error('No permissions returned. Is the jmac-suite stack running?')
  process.exit(1)
}

const body = [
  '// Generated by `npm run db:permissions` from public.permissions — do not edit.',
  '// A typo in a permission key should fail compilation, not silently deny access',
  '// at runtime. Regenerate whenever the permission catalogue changes.',
  '',
  'export type PermissionKey =',
  ...keys.map((key) => `  | '${key}'`),
  '',
].join('\n')

writeFileSync('src/types/permissions.generated.ts', body)
console.log(`Wrote ${keys.length} permission keys to src/types/permissions.generated.ts`)
